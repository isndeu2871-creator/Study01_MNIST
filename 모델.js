/* desktop_version/model.py 의 순전파를 자바스크립트로 다시 쓴 것.
   외부 라이브러리를 쓰지 않는다.

     입력 1x28x28
      → 합성곱1(1→32, 3x3, 패딩 1) → ReLU → 최대풀링 2x2      (32x14x14)
      → 합성곱2(32→64, 3x3, 패딩 1) → ReLU → 최대풀링 2x2     (64x7x7)
      → 펼치기(3136) → 전결합1(3136→128) → ReLU
      → 전결합2(128→10) → 소프트맥스

   드롭아웃은 예측할 때 아무 일도 하지 않으므로 옮기지 않았다. */
const 모델 = (function () {
  let 텐서 = null;
  let 정보 = null;

  async function 불러오기(폴더) {
    폴더 = 폴더 || "";
    const 문서 = await fetch(폴더 + "가중치정보.json").then(function (응답) {
      if (!응답.ok) throw new Error("가중치정보.json 을 읽지 못했습니다 (" + 응답.status + ")");
      return 응답.json();
    });
    const 버퍼 = await fetch(폴더 + "가중치.bin").then(function (응답) {
      if (!응답.ok) throw new Error("가중치.bin 을 읽지 못했습니다 (" + 응답.status + ")");
      return 응답.arrayBuffer();
    });
    텐서 = {};
    문서.텐서.forEach(function (항목) {
      텐서[항목.이름] = new Float32Array(버퍼, 항목.위치, 항목.개수);
    });
    정보 = 문서;
    return 문서;
  }

  /* 합성곱. 보폭 1, 패딩은 0으로 채운다. 원본은 (채널, 크기, 크기)를 한 줄로 펼친 배열. */
  function 합성곱(원본, 입력크기, 입력채널, 가중치, 편향, 출력채널, 커널, 패딩, 렐루) {
    const 출력크기 = 입력크기 + 2 * 패딩 - 커널 + 1;
    const 면 = 출력크기 * 출력크기;
    const 결과 = new Float32Array(출력채널 * 면);
    for (let 바깥 = 0; 바깥 < 출력채널; 바깥++) {
      const 가중치시작 = 바깥 * 입력채널 * 커널 * 커널;
      const 기본값 = 편향[바깥];
      for (let 세로 = 0; 세로 < 출력크기; 세로++) {
        for (let 가로 = 0; 가로 < 출력크기; 가로++) {
          let 합 = 기본값;
          for (let 채널 = 0; 채널 < 입력채널; 채널++) {
            const 원본면 = 채널 * 입력크기 * 입력크기;
            const 가중치면 = 가중치시작 + 채널 * 커널 * 커널;
            for (let 커널세로 = 0; 커널세로 < 커널; 커널세로++) {
              const 읽을세로 = 세로 + 커널세로 - 패딩;
              if (읽을세로 < 0 || 읽을세로 >= 입력크기) continue;
              const 원본줄 = 원본면 + 읽을세로 * 입력크기;
              const 가중치줄 = 가중치면 + 커널세로 * 커널;
              for (let 커널가로 = 0; 커널가로 < 커널; 커널가로++) {
                const 읽을가로 = 가로 + 커널가로 - 패딩;
                if (읽을가로 < 0 || 읽을가로 >= 입력크기) continue;
                합 += 원본[원본줄 + 읽을가로] * 가중치[가중치줄 + 커널가로];
              }
            }
          }
          결과[바깥 * 면 + 세로 * 출력크기 + 가로] = 렐루 && 합 < 0 ? 0 : 합;
        }
      }
    }
    return 결과;
  }

  /* 2x2 최대풀링 */
  function 최대풀링(원본, 입력크기, 채널수) {
    const 출력크기 = 입력크기 >> 1;
    const 결과 = new Float32Array(채널수 * 출력크기 * 출력크기);
    for (let 채널 = 0; 채널 < 채널수; 채널++) {
      const 원본면 = 채널 * 입력크기 * 입력크기;
      const 결과면 = 채널 * 출력크기 * 출력크기;
      for (let 세로 = 0; 세로 < 출력크기; 세로++) {
        for (let 가로 = 0; 가로 < 출력크기; 가로++) {
          const 자리 = 원본면 + 2 * 세로 * 입력크기 + 2 * 가로;
          let 최대 = 원본[자리];
          if (원본[자리 + 1] > 최대) 최대 = 원본[자리 + 1];
          if (원본[자리 + 입력크기] > 최대) 최대 = 원본[자리 + 입력크기];
          if (원본[자리 + 입력크기 + 1] > 최대) 최대 = 원본[자리 + 입력크기 + 1];
          결과[결과면 + 세로 * 출력크기 + 가로] = 최대;
        }
      }
    }
    return 결과;
  }

  function 전결합(원본, 가중치, 편향, 출력수, 렐루) {
    const 입력수 = 원본.length;
    const 결과 = new Float32Array(출력수);
    for (let 바깥 = 0; 바깥 < 출력수; 바깥++) {
      let 합 = 편향[바깥];
      const 줄 = 바깥 * 입력수;
      for (let 안 = 0; 안 < 입력수; 안++) 합 += 가중치[줄 + 안] * 원본[안];
      결과[바깥] = 렐루 && 합 < 0 ? 0 : 합;
    }
    return 결과;
  }

  function 소프트맥스(로짓) {
    let 최대 = -Infinity;
    for (let i = 0; i < 로짓.length; i++) if (로짓[i] > 최대) 최대 = 로짓[i];
    let 합 = 0;
    const 결과 = new Float32Array(로짓.length);
    for (let i = 0; i < 로짓.length; i++) { 결과[i] = Math.exp(로짓[i] - 최대); 합 += 결과[i]; }
    for (let i = 0; i < 로짓.length; i++) 결과[i] /= 합;
    return 결과;
  }

  /* 밝기배열: 길이 784, 값 0~1 (전처리.js 가 낸 것). 정규화는 여기서 한다. */
  function 예측(밝기배열) {
    if (!텐서) throw new Error("모델이 아직 준비되지 않았습니다.");
    const 평균 = 정보.정규화.평균;
    const 표준편차 = 정보.정규화.표준편차;
    const 입력 = new Float32Array(784);
    for (let i = 0; i < 784; i++) 입력[i] = (밝기배열[i] - 평균) / 표준편차;

    let 값 = 합성곱(입력, 28, 1, 텐서["합성곱1.weight"], 텐서["합성곱1.bias"], 32, 3, 1, true);
    값 = 최대풀링(값, 28, 32);                                                        // 32x14x14
    값 = 합성곱(값, 14, 32, 텐서["합성곱2.weight"], 텐서["합성곱2.bias"], 64, 3, 1, true);
    값 = 최대풀링(값, 14, 64);                                                        // 64x7x7
    값 = 전결합(값, 텐서["전결합1.weight"], 텐서["전결합1.bias"], 128, true);
    return 소프트맥스(전결합(값, 텐서["전결합2.weight"], 텐서["전결합2.bias"], 10, false));
  }

  function 설명() { return 정보; }

  return { 불러오기: 불러오기, 예측: 예측, 설명: 설명 };
})();
