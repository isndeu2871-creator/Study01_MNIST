"""그린 그림을 MNIST와 같은 모양으로 다듬는다.

MNIST는 숫자를 20x20 칸에 맞춘 뒤 밝기 무게중심을 28x28 칸 가운데에 놓은 자료다.
사람이 그린 그림을 그대로 넣으면 잘 맞지 않으므로 같은 순서로 다듬는다.

    1단계 여백 자르기      획이 있는 영역만 남긴다
    2단계 20x20 축소       비율을 유지하며 긴 변을 20픽셀로 줄인다
    3단계 무게중심 이동     밝기 무게중심을 28x28 칸 가운데로 옮긴다

web_version/전처리.js 가 이 3단계를 그대로 옮긴 것이다.
한 곳만 다르다. 여기서는 PIL의 LANCZOS로 줄이고, 브라우저에서는 그것을 그대로
재현할 수 없어 면적 평균으로 줄인다.
"""
import numpy as np
from PIL import Image

# MNIST 학습에 쓰는 정규화 상수. 이 값의 출처는 이 파일 하나로 유지한다.
평균 = 0.1307
표준편차 = 0.3081

# 이 밝기보다 밝으면 획으로 본다
획기준 = 0.08

칸크기 = 28
숫자칸 = 20


def 여백자르기(회색그림):
    """획이 있는 영역만 남긴다. 획이 하나도 없으면 None."""
    배열 = np.asarray(회색그림, dtype=np.float32) / 255.0
    세로, 가로 = np.nonzero(배열 > 획기준)
    if len(가로) == 0:
        return None
    return 회색그림.crop((int(가로.min()), int(세로.min()),
                        int(가로.max()) + 1, int(세로.max()) + 1))


def 축소하고_가운데두기(잘린그림):
    """비율을 유지하며 긴 변을 20픽셀로 줄이고 28x28 칸 한가운데에 붙인다."""
    너비, 높이 = 잘린그림.size
    비율 = 숫자칸 / max(너비, 높이)
    새너비 = max(1, int(np.floor(너비 * 비율 + 0.5)))
    새높이 = max(1, int(np.floor(높이 * 비율 + 0.5)))
    줄인그림 = 잘린그림.resize((새너비, 새높이), Image.LANCZOS)
    칸 = Image.new("L", (칸크기, 칸크기), 0)
    칸.paste(줄인그림, ((칸크기 - 새너비) // 2, (칸크기 - 새높이) // 2))
    return 칸


def 무게중심이동(배열):
    """밝기 무게중심을 칸 한가운데로 옮긴다."""
    무게 = 배열.sum()
    if 무게 == 0:
        return 배열
    세로좌표, 가로좌표 = np.indices(배열.shape)
    가운데 = (칸크기 - 1) / 2
    옮길가로 = int(np.floor(가운데 - (배열 * 가로좌표).sum() / 무게 + 0.5))
    옮길세로 = int(np.floor(가운데 - (배열 * 세로좌표).sum() / 무게 + 0.5))
    if 옮길가로 == 0 and 옮길세로 == 0:
        return 배열
    옮긴배열 = np.zeros_like(배열)
    원본세로 = slice(max(0, -옮길세로), 칸크기 - max(0, 옮길세로))
    새세로 = slice(max(0, 옮길세로), 칸크기 - max(0, -옮길세로))
    원본가로 = slice(max(0, -옮길가로), 칸크기 - max(0, 옮길가로))
    새가로 = slice(max(0, 옮길가로), 칸크기 - max(0, -옮길가로))
    옮긴배열[새세로, 새가로] = 배열[원본세로, 원본가로]
    return 옮긴배열


def 전처리(그림):
    """흰 획 / 검은 바탕 그림 → 28x28 밝기 배열(0~1). 빈 그림이면 None."""
    회색그림 = 그림.convert("L")
    잘린그림 = 여백자르기(회색그림)
    if 잘린그림 is None:
        return None
    칸 = 축소하고_가운데두기(잘린그림)
    배열 = np.asarray(칸, dtype=np.float32) / 255.0
    return 무게중심이동(배열)


def 정규화(배열):
    """전처리한 배열을 학습 때와 같은 분포로 맞춘다."""
    return (배열 - 평균) / 표준편차
